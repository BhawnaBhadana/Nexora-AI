function renderCode(text) {
  const output = document.getElementById("code-output");
  const parts = text.split("EXPLANATION:");
  const codePart = parts[0].replace("CODE:", "").trim();
  const explainPart = parts[1] ? parts[1].trim() : "";
  let html = `<pre class="code-result">${escapeHtml(codePart)}</pre>`;
  if (explainPart) html += `<div class="code-explain"><strong>Explanation:</strong><br>${explainPart.replace(/\n/g, "<br>")}</div>`;
  output.innerHTML = html;
}

function escapeHtml(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

