function renderNotes(text, topic) {
  const output = document.getElementById("notes-output");
  let html = `<div class="notes-heading">${topic} — complete notes</div>`;
  text.split("\n").forEach(line => {
    const t = line.trim();
    if (t.startsWith("SECTION:")) html += `<div class="notes-section-title">${t.replace("SECTION:", "").trim()}</div>`;
    else if (t.startsWith("CONTENT:")) html += `<div class="notes-text">${t.replace("CONTENT:", "").trim()}</div>`;
    else if (t) html += `<div class="notes-text">${t}</div>`;
  });
  output.innerHTML = html;
}

