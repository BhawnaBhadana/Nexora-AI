async function sendDoubt() {
  const input = document.getElementById("doubt-input");
  const msg = input.value.trim();
  if (!msg) return;
  input.value = "";
  appendBubble(msg, "user", "chat-messages");
  showTyping("chat-messages", "ai");
  trackActivity("doubt");
  try {
    const reply = await askAI(
      `You are Nexora AI, a friendly study assistant for Indian college students.
       Answer doubts clearly and concisely. Use simple language with real-life examples.
       Use **bold** for important terms. Keep answers under 200 words unless needed.`,
      msg
    );
    removeTyping("chat-messages");
    appendBubble(reply, "ai", "chat-messages");
  } catch (err) {
    removeTyping("chat-messages");
    appendBubble("Sorry, something went wrong. Please make sure the backend is running.", "ai", "chat-messages");
  }
}

function appendBubble(text, type, areaId) {
  const area = document.getElementById(areaId);
  const wrap = document.createElement("div");
  wrap.className = `bubble-wrap ${type === "user" ? "user" : ""}`;
  const avatar = document.createElement("div");
  const isCareer = areaId === "career-messages";
  avatar.className = `bub-avatar ${type === "ai" ? (isCareer ? "career-av" : "ai-av") : "usr-av"}`;
  avatar.innerHTML = type === "ai"
    ? (isCareer ? '<i class="ti ti-briefcase"></i>' : '<i class="ti ti-brain"></i>')
    : currentUser.name.charAt(0).toUpperCase();
  const bubble = document.createElement("div");
  bubble.className = `bubble ${type === "ai" ? (isCareer ? "career-bubble" : "ai-bubble") : "usr-bubble"}`;
  bubble.innerHTML = text.replace(/\n/g, "<br>").replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>");
  wrap.appendChild(avatar);
  wrap.appendChild(bubble);
  area.appendChild(wrap);
  area.scrollTop = area.scrollHeight;
}

