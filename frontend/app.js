    const data = await res.json();
    if (!data.result) throw new Error("No result");
    output.innerHTML = `<div class="notes-heading">Solution</div><div class="notes-text" style="line-height:1.8">${data.result.replace(/\n/g, "<br>").replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")}</div>`;
