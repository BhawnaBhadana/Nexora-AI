async function generateResume() {
  const userData = {
    name: document.getElementById("r-name").value.trim(),
    email: document.getElementById("r-email").value.trim(),
    phone: document.getElementById("r-phone").value.trim(),
    location: document.getElementById("r-location").value.trim(),
    linkedin: document.getElementById("r-linkedin").value.trim(),
    github: document.getElementById("r-github").value.trim(),
    college: document.getElementById("r-college").value.trim(),
    degree: document.getElementById("r-degree").value.trim(),
    year: document.getElementById("r-year").value.trim(),
    cgpa: document.getElementById("r-cgpa").value.trim(),
    skills: document.getElementById("r-skills").value.trim(),
    projects: document.getElementById("r-projects").value.trim(),
    experience: document.getElementById("r-experience").value.trim(),
    achievements: document.getElementById("r-achievements").value.trim(),
    objective: document.getElementById("r-objective").value.trim()
  };
  if (!userData.name || !userData.email || !userData.college) {
    return alert("Please fill in at least name, email and college");
  }
  const output = document.getElementById("resume-output");
  output.innerHTML = '<div class="loading"><div class="dot"></div><div class="dot"></div><div class="dot"></div>&nbsp; Building your resume...</div>';
  try {
    const res = await fetch(`${BACKEND}/api/ai/resume`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ userData })
    });
    const data = await res.json();
    if (!data.result) throw new Error("No result");
    output.innerHTML = data.result;
  } catch (err) {
    output.innerHTML = '<div class="empty-state"><i class="ti ti-alert-circle"></i><p>Error generating resume. Make sure backend is running.</p></div>';
  }
}

function downloadResume() {
  const output = document.getElementById("resume-output");
  if (!output.innerHTML || output.querySelector(".empty-state")) {
    return alert("Please generate your resume first");
  }
  const printWindow = window.open("", "_blank");
  printWindow.document.write(`<!DOCTYPE html><html><head><title>Resume — Nexora AI</title>
    <style>body{font-family:Arial,sans-serif;margin:0;padding:20px}@media print{body{margin:0;padding:0}}</style>
    </head><body>${output.innerHTML}</body></html>`);
  printWindow.document.close();
  printWindow.focus();
  setTimeout(() => { printWindow.print(); printWindow.close(); }, 500);
}

