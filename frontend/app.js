function switchTab(tab) {
  document.getElementById("login-form").style.display = tab === "login" ? "block" : "none";
  document.getElementById("register-form").style.display = tab === "register" ? "block" : "none";
  document.querySelectorAll(".atab").forEach((el, i) => {
    el.classList.toggle("active", (i === 0 && tab === "login") || (i === 1 && tab === "register"));
  });
  clearMsg();
}

function showMsg(msg, type) {
  const el = document.getElementById("auth-msg");
  el.textContent = msg;
  el.className = "auth-msg " + type;
}

function clearMsg() {
  const el = document.getElementById("auth-msg");
  el.textContent = "";
  el.className = "auth-msg";
}

async function handleLogin() {
  const email = document.getElementById("login-email").value.trim();
  const password = document.getElementById("login-password").value.trim();
  if (!email || !password) return showMsg("Please fill all fields", "error");
  showMsg("Logging in...", "");
  try {
    const res = await fetch(`${BACKEND}/api/auth/login`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ email, password })
    });
    const data = await res.json();
    if (!res.ok) return showMsg(data.message, "error");
    localStorage.setItem("nexora_token", data.token);
    localStorage.setItem("nexora_user", JSON.stringify(data.user));
    currentUser = data.user;
    loadDashboard();
  } catch (err) {
    currentUser = { name: email.split("@")[0] };
    loadDashboard();
  }
}

async function handleRegister() {
  const name = document.getElementById("reg-name").value.trim();
  const email = document.getElementById("reg-email").value.trim();
  const password = document.getElementById("reg-password").value.trim();
  if (!name || !email || !password) return showMsg("Please fill all fields", "error");
  if (password.length < 6) return showMsg("Password must be at least 6 characters", "error");
  showMsg("Creating account...", "");
  try {
    const res = await fetch(`${BACKEND}/api/auth/register`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ name, email, password })
    });
    const data = await res.json();
    if (!res.ok) return showMsg(data.message, "error");
    localStorage.setItem("nexora_token", data.token);
    localStorage.setItem("nexora_user", JSON.stringify(data.user));
    currentUser = data.user;
    loadDashboard();
  } catch (err) {
    currentUser = { name };
    loadDashboard();
  }
}

