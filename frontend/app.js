async function sendCareerMsg() {
  const input = document.getElementById("career-input");
  const msg = input.value.trim();
  if (!msg) return;
  input.value = "";
  appendBubble(msg, "user", "career-messages");
  showTyping("career-messages", "career");
  try {
    const reply = await askAI(
      `You are Nexora Career Guide, an expert career counsellor for Indian college students.
       Give honest, practical, India-specific career advice.
       Cover: jobs, salaries, skills, certifications, internships, placements, higher studies, freelancing.
       Be direct and specific — mention real companies, real salary ranges, real platforms.
       Use **bold** for important points. Keep responses clear and under 300 words.
       Always be encouraging and realistic about Indian job market.`,
      msg
    );
    removeTyping("career-messages");
    appendBubble(reply, "ai", "career-messages");
  } catch (err) {
    removeTyping("career-messages");
    appendBubble("Sorry, something went wrong. Please make sure the backend is running.", "ai", "career-messages");
  }
}

function askCareerTopic(topic) {
  document.getElementById("career-input").value = topic;
  sendCareerMsg();
}

